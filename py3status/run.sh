#!/usr/bin/env bash
# i3bar status_command: main.conf + this machine's section of order.conf
set -euo pipefail

here=$(dirname "$(readlink -f "$0")")
orders="$here/order.conf"

key=$(hostname)
[ "$(whoami)" = star ] && key=star
grep -qxF "[$key]" "$orders" || key=default

conf="${XDG_RUNTIME_DIR:-/tmp}/py3status.$(id -u).conf"
{
  printf '# Generated by %s; edit main.conf or order.conf instead.\n' "$0"
  cat "$here/main.conf"
  awk -v want="[$key]" '/^\[.*\]$/ { on = ($0 == want); next } on' "$orders"
} >"$conf.tmp"
mv "$conf.tmp" "$conf"

exec py3status -c "$conf"
